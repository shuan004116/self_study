DISPATCHER_EXTRACTION_PROMPT = (
    "分析以下用户问题，判断其学科领域和意图类型。\n"
    "只输出JSON格式：\n"
    '{"intent": "答疑|出题|规划|总结|代码", "subject": "数学|计算机|物理|人文|跨学科", '
    '"reasoning": "分类理由"}'
)


def format_system_prompt(role: str, context: str = "") -> str:
    """Format system prompt for a given agent role with optional context."""
    base = SYSTEM_PROMPTS.get(role, "")
    if context:
        return f"{base}\n\n上下文信息：\n{context}"
    return base
